"""Describe the gRPC contract for the browser client (ui/rpc.js) from the generated Python stubs.

Usage: python scripts/generate-ui-schema.py [output]   (default: ui/schema.js, ignored by git)
"""
import json
import sys
from pathlib import Path
from google.protobuf.descriptor import FieldDescriptor as F

root = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(root / 'backend'))
from hardware.v1 import hardware_pb2  # noqa: E402

TYPES = {F.TYPE_STRING: 'string', F.TYPE_INT64: 'int64', F.TYPE_INT32: 'int32', F.TYPE_BOOL: 'bool',
         F.TYPE_DOUBLE: 'double', F.TYPE_MESSAGE: 'message'}


def describe(message):
    fields = []
    for f in message.fields:
        if f.type not in TYPES:
            raise SystemExit(f'{message.full_name}.{f.name}: field type {f.type} is not supported by ui/rpc.js')
        fields.append({'n': f.number, 'name': f.name, 'type': TYPES[f.type], 'repeated': f.is_repeated,
                       'optional': f.has_presence and f.containing_oneof is not None,
                       'message': f.message_type.full_name if f.type == F.TYPE_MESSAGE else None})
    return fields


schema = {'messages': {}, 'methods': {}}
for message in hardware_pb2.DESCRIPTOR.message_types_by_name.values():
    schema['messages'][message.full_name] = describe(message)
for service in hardware_pb2.DESCRIPTOR.services_by_name.values():
    for method in service.methods:
        schema['methods'][method.name] = {'service': service.full_name, 'request': method.input_type.full_name,
                                           'response': method.output_type.full_name}
# Well-known types the contract uses; Struct is decoded by hand in rpc.js.
schema['messages']['google.protobuf.Timestamp'] = [
    {'n': 1, 'name': 'seconds', 'type': 'int64', 'repeated': False, 'optional': False, 'message': None},
    {'n': 2, 'name': 'nanos', 'type': 'int32', 'repeated': False, 'optional': False, 'message': None}]

target = Path(sys.argv[1]) if len(sys.argv) > 1 else root / 'ui' / 'schema.js'
target.write_text('// Generated by scripts/generate-ui-schema.py from proto/hardware/v1/hardware.proto. Do not edit.\n'
                  'window.HARDWARE_SCHEMA = ' + json.dumps(schema, indent=1) + ';\n')
print('Wrote', target)
