import os
from pathlib import Path
from uuid import uuid4
from playwright.sync_api import sync_playwright, expect


def test_admin_ui_api_roundtrip():
    base=os.environ.get('TEST_BASE_URL','http://localhost:8080')
    code=Path(os.environ['DEV_LOGIN_CODE_FILE']).read_text().strip()
    with sync_playwright() as p:
        browser=p.chromium.launch(args=['--no-sandbox'])
        page=browser.new_page(viewport={'width':1100,'height':800})
        page.on('dialog',lambda dialog:dialog.accept())
        page.goto(base+'/?local=1')
        page.get_by_label('Local development code').fill(code)
        page.get_by_role('button',name='Sign in locally').click()
        expect(page.get_by_role('heading',name='Inventory dashboard')).to_be_visible()
        page.get_by_role('button',name='Hardware',exact=True).click()
        page.get_by_role('button',name='Add hardware',exact=True).click()
        tag='E2E-'+uuid4().hex[:8]
        dialog=page.get_by_role('dialog')
        dialog.get_by_label('Name',exact=True).fill(tag)
        dialog.get_by_label('Category',exact=True).fill('Testing')
        dialog.get_by_label('Unique asset tag').fill(tag)
        dialog.get_by_label('Total units').fill('4')
        dialog.get_by_label('Reason (required)').fill('Browser inventory test')
        dialog.get_by_role('button',name='Review and confirm').click()
        expect(dialog).not_to_be_visible()
        page.get_by_label('Name / asset tag prefix').fill(tag)
        page.get_by_role('button',name='Search / filter').click()
        row=page.locator('tr').filter(has_text=tag)
        expect(row).to_have_count(1)
        row.get_by_role('button',name='Adjust stock').click()
        dialog.get_by_label('Change in total').fill('-1')
        dialog.get_by_label('Reason (required)').fill('Remove damaged unit')
        dialog.get_by_role('button',name='Review and confirm').click()
        expect(dialog).not_to_be_visible()
        expect(row.locator('td').nth(2)).to_have_text('3')
        row.get_by_role('button',name='Audit').click()
        expect(page.get_by_text('adjust',exact=False).first).to_be_visible()
        # Reserve through the UI, then check out and check in without API writes.
        hardware=page.request.get(base+'/api/hardware',params={'q':tag}).json()['items'][0]
        project='E2E-project-'+uuid4().hex[:8]
        page.get_by_role('button',name='Project inventory',exact=True).click()
        page.get_by_role('button',name='Set project allocation',exact=True).click()
        dialog.get_by_label('Hardware ID',exact=True).fill(hardware['_id'])
        dialog.get_by_label('External project ID',exact=True).fill(project)
        dialog.get_by_label('New allocated total').fill('3')
        dialog.get_by_label('Reason (required)').fill('Reserve for browser checkout test')
        dialog.get_by_role('button',name='Review and confirm').click()
        expect(dialog).not_to_be_visible()
        page.get_by_role('button',name='Checkout management',exact=True).click()
        page.get_by_role('button',name='Check out hardware',exact=True).click()
        dialog.get_by_label('Hardware ID',exact=True).fill(hardware['_id'])
        dialog.get_by_label('External project ID',exact=True).fill(project)
        dialog.get_by_label('Borrower ID',exact=True).fill('browser-borrower')
        dialog.get_by_label('Quantity to check out').fill('4')
        dialog.get_by_label('Reason (required)').fill('Issue equipment to borrower')
        dialog.get_by_role('button',name='Review and confirm').click()
        expect(dialog.get_by_role('alert')).to_have_text('Insufficient project stock')
        expect(dialog).to_be_visible()
        dialog.get_by_label('Quantity to check out').fill('2')
        dialog.get_by_role('button',name='Review and confirm').click()
        expect(dialog).not_to_be_visible()
        checkout_row=page.locator('tr').filter(has_text=project)
        expect(checkout_row).to_have_count(1)
        expect(checkout_row.locator('td').nth(3)).to_have_text('2')
        checkout_row.get_by_role('button',name='Check in',exact=True).click()
        quantity=dialog.get_by_label('Quantity to check in')
        expect(quantity).to_have_attribute('min','1')
        expect(quantity).to_have_attribute('max','2')
        quantity.fill('3')
        dialog.get_by_label('Reason (required)').fill('Partial equipment return')
        dialog.get_by_role('button',name='Review and confirm').click()
        expect(dialog).to_be_visible()  # Native validation rejects an excessive return.
        quantity.fill('1')
        dialog.get_by_role('button',name='Review and confirm').click()
        expect(dialog).not_to_be_visible()
        expect(checkout_row.locator('td').nth(3)).to_have_text('1')
        checkout_row.get_by_role('button',name='Check in',exact=True).click()
        expect(quantity).to_have_value('1')
        dialog.get_by_label('Reason (required)').fill('Return remaining equipment')
        dialog.get_by_role('button',name='Review and confirm').click()
        expect(dialog).not_to_be_visible()
        expect(checkout_row).to_have_count(0)
        page.get_by_label('Show',exact=True).select_option('false')
        page.get_by_role('button',name='Search / filter').click()
        expect(checkout_row.locator('td').nth(3)).to_have_text('0')
        expect(checkout_row.get_by_role('button',name='Check in',exact=True)).to_be_disabled()
        assert page.request.get(base+'/api/hardware/'+hardware['_id']).json()['out']==0
        # The allocation shortcut prefills immutable IDs and limits project capacity.
        page.get_by_role('button',name='Project inventory',exact=True).click()
        page.get_by_label('External project ID',exact=True).fill(project)
        page.get_by_role('button',name='Search / filter').click()
        page.locator('tr').filter(has_text=project).get_by_role('button',name='Check out',exact=True).click()
        expect(dialog.get_by_label('Hardware ID',exact=True)).to_have_value(hardware['_id'])
        expect(dialog.get_by_label('Hardware ID',exact=True)).to_have_attribute('readonly','')
        expect(dialog.get_by_label('External project ID',exact=True)).to_have_value(project)
        expect(dialog.get_by_label('Quantity to check out')).to_have_attribute('max','3')
        dialog.get_by_role('button',name='Cancel',exact=True).click()
        # No credentials or bearer tokens persist in web storage.
        assert page.evaluate('Object.keys(localStorage).length + Object.keys(sessionStorage).length')==0
        cookie=next(c for c in page.context.cookies() if c['name']=='hardware_session')
        assert cookie['httpOnly'] and cookie['sameSite']=='Lax'
        page.get_by_role('button',name='Sign out',exact=True).click()
        expect(page.get_by_role('heading',name='Administrator sign in')).to_be_visible()
        browser.close()
